import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  apiKeyArgs,
  archiveProblems,
  exportOptionsPlist,
  iosCleanBlocker,
  outputPath,
  parseOptions,
  PREBUILD_MARKER,
  type ArchiveFacts,
} from './testflight-lib'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(root, '../..')
function main() {
  const options = parseOptions(process.argv.slice(2))
  const gitDir = spawnSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], {
    cwd: repo,
    encoding: 'utf8',
  })
  if (gitDir.status !== 0) throw new Error('Cannot locate repository for signing-key safety check')
  const commonDir = gitDir.stdout.trim()
  const keyArgs = apiKeyArgs(
    process.env,
    repo,
    basename(commonDir) === '.git' ? [dirname(commonDir)] : [commonDir],
  )
  const team = process.env.DIRECTION_IOS_TEAM_ID?.trim() || 'U9ATA49N28'
  exportOptionsPlist(team, 'export')
  if (process.platform !== 'darwin') throw new Error('iOS builds require macOS and Xcode')
  if (options.mode !== 'simulator' && !options.dryRun && !keyArgs.length) {
    const result = spawnSync('defaults', ['read', 'com.apple.dt.Xcode', 'IDEProvisioningTeamByIdentifier'], {
      encoding: 'utf8',
    })
    if (result.status !== 0 || !result.stdout.includes(team))
      throw new Error(`Xcode has no Apple account for team ${team}; sign in or configure ASC API key`)
  }
  const output = outputPath(root, options.buildNumber)
  const env = {
    ...process.env,
    DIRECTION_MOBILE_BUILD_NUMBER: options.buildNumber,
    DIRECTION_IOS_TEAM_ID: team,
    EXPO_NO_GIT_STATUS: '1',
    CI: '1',
  }
  const run = (command: string, args: string[]) => {
    const publicArgs = args.map((arg, i) =>
      i > 0 &&
      ['-authenticationKeyPath', '-authenticationKeyID', '-authenticationKeyIssuerID'].includes(args[i - 1])
        ? '[redacted]'
        : arg,
    )
    console.log(`$ ${command} ${publicArgs.join(' ')}`)
    if (options.dryRun) return
    const result = spawnSync(command, args, { cwd: root, env, stdio: 'inherit' })
    if (result.status !== 0)
      throw new Error(`${command} exited with ${result.status ?? result.signal ?? result.error?.message}`)
  }
  if (!options.dryRun) mkdirSync(output, { recursive: true })
  const ignored = spawnSync('git', ['check-ignore', '-q', 'apps/mobile/ios'], { cwd: repo })
  if (ignored.status !== 0) throw new Error('apps/mobile/ios must be git-ignored before prebuild --clean')
  const iosDir = join(root, 'ios')
  const blocker = iosCleanBlocker(existsSync(iosDir), existsSync(join(iosDir, PREBUILD_MARKER)))
  if (blocker) throw new Error(blocker)
  const expo = Bun.resolveSync('expo/bin/cli', root)
  run(process.execPath, [expo, 'prebuild', '--clean', '--platform', 'ios'])
  if (!options.dryRun) writeFileSync(join(iosDir, PREBUILD_MARKER), 'generated by apps/mobile/scripts/testflight.ts\n')
  const ios = join(root, 'ios')
  const projects = options.dryRun
    ? ['app.xcodeproj']
    : readdirSync(ios).filter((x) => x.endsWith('.xcodeproj'))
  if (projects.length !== 1) throw new Error('Expected exactly one Xcode project')
  const name = basename(projects[0], '.xcodeproj'),
    workspace = join(ios, `${name}.xcworkspace`)
  const common = [
    '-workspace',
    workspace,
    '-scheme',
    name,
    '-configuration',
    'Release',
    '-derivedDataPath',
    join(output, 'DerivedData'),
  ]
  if (options.mode === 'simulator') {
    run('xcodebuild', [
      ...common,
      '-sdk',
      'iphonesimulator',
      '-destination',
      'generic/platform=iOS Simulator',
      'CODE_SIGNING_ALLOWED=NO',
      'build',
    ])
    const app = join(output, 'DerivedData/Build/Products/Release-iphonesimulator', `${name}.app`)
    if (!options.dryRun && !existsSync(app)) throw new Error(`Simulator app missing: ${app}`)
    console.log(`Simulator app: ${app}`)
    return
  }
  const archive = join(output, `${name}.xcarchive`)
  const signing = [
    '-allowProvisioningUpdates',
    '-allowProvisioningDeviceRegistration',
    ...keyArgs,
    `DEVELOPMENT_TEAM=${team}`,
    'CODE_SIGN_STYLE=Automatic',
    `CURRENT_PROJECT_VERSION=${options.buildNumber}`,
  ]
  run('xcodebuild', [
    ...common,
    '-destination',
    'generic/platform=iOS',
    '-archivePath',
    archive,
    ...signing,
    'archive',
  ])
  if (!options.dryRun) {
    const appsDir = join(archive, 'Products/Applications')
    const apps = readdirSync(appsDir)
      .filter((x) => x.endsWith('.app'))
      .map((x) => join(appsDir, x))
    const plistValue = (file: string, key: string): string | null => {
      const result = spawnSync('/usr/libexec/PlistBuddy', ['-c', `Print :${key}`, file], { encoding: 'utf8' })
      return result.status === 0 ? result.stdout.trim() : null
    }
    const app = apps[0],
      config = app && join(app, 'EXConstants.bundle/app.config')
    const facts: ArchiveFacts = {
      apps: apps.map((path) => ({
        bundleId: plistValue(join(path, 'Info.plist'), 'CFBundleIdentifier'),
        version: plistValue(join(path, 'Info.plist'), 'CFBundleVersion'),
      })),
      embedded: config && existsSync(config) ? JSON.parse(readFileSync(config, 'utf8')) : null,
      extensions: app && existsSync(join(app, 'PlugIns')) ? readdirSync(join(app, 'PlugIns')).length : 0,
    }
    const errors = archiveProblems(facts, options.buildNumber)
    if (errors.length) throw new Error(`Archive verification failed: ${errors.join('; ')}`)
    console.log(`Verified archive: ${options.buildNumber}`)
  }
  const plist = join(output, 'ExportOptions.plist'),
    destination = options.mode === 'export' ? 'export' : 'upload'
  if (!options.dryRun) writeFileSync(plist, exportOptionsPlist(team, destination))
  run('xcodebuild', [
    '-exportArchive',
    '-archivePath',
    archive,
    '-exportOptionsPlist',
    plist,
    '-exportPath',
    join(output, 'export'),
    '-allowProvisioningUpdates',
    ...keyArgs,
  ])
  if (options.dryRun) {
    console.log('Dry run only; no archive or export was created.')
    return
  }
  console.log(
    `${destination === 'export' ? 'Exported' : 'Uploaded'} build ${options.buildNumber}: ${join(output, 'export')}`,
  )
}
try {
  main()
} catch (error) {
  console.error(`mobile-testflight: ${error instanceof Error ? error.message : String(error)}`)
  process.exitCode = 1
}
