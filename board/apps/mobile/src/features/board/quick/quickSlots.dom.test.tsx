// PR #43 리뷰 6(iOS): known 은 잘 읽거나 쓴 원문만 — 읽기 실패는 known 이 되지 않고, 전제·재검사 읽기 실패는 언제나 "다름"(쓰기 0건 + 읽기 실패 안내)
