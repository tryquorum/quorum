// PR #43 리뷰 7(iOS 확인): known 을 처음 잡거나 다시 잡을 때 화면이 복원한 값과 읽은 값을 비교 — 다르면 known 은 읽은 값으로 두되 충돌(쓰기·비우기 0건)
