// PR #43 리뷰: 기기 저장의 한 줄 대기열(초기화·다시 읽기·새 제출 순서)과 자리별 저장(한 자리의 깨짐·버리기가 다른 자리에 닿지 않음)을
// 실제 화면(한 줄·상세 시트)과 실제 SmallStore 로 봐요. 하네스는 __tests__/quickHarness.ts.
import { describe, expect, test } from 'bun:test'
import { slotName } from '@direction-board/contracts/slot-store'
import { act, alerts, BAR, click, confirms, created, disk, failReads, failWrites, gate, h, holdWrite, hooks, mount, q, QuickAddBar, React, remount, settle, SHEET, sheetEl, store, typeInto, useQuickHarness, useStoredIn, win } from './__tests__/quickHarness'
import { isPending, SLOTS } from './recovery'

useQuickHarness()
const anyJson = (_v: unknown): _v is unknown => true
const rec = (id: string, title: string) => ({ id, from: 'item', text: title, ref: null, scope: 'http://127.0.0.1:3181|anon', draft: { kind: 'todo', title, at: null, areaId: null, tags: [], note: '', props: [], boardId: 'pb' } })
const fileOf = (slot: string) => disk.get(slotName(SLOTS, slot))
const alertWith = (t: string) => [...document.querySelectorAll('[role="alert"]')].find((x) => (x.textContent ?? '').includes(t)) as HTMLElement | undefined
const buttonIn = (box: HTMLElement | undefined, label: string) => [...(box?.querySelectorAll('button') ?? [])].find((x) => (x.textContent ?? '').trim() === label)
const press = async (box: HTMLElement | undefined, label: string) => { const b = buttonIn(box, label); expect(b).toBeTruthy(); await click(b!) }
const barInput = () => q<HTMLInputElement>('input[aria-label="할 일 추가"]')!
const titleInput = () => q<HTMLInputElement>('input[aria-label="제목"]')!
const enter = async () => { await act(async () => { barInput().dispatchEvent(new win.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }) as unknown as Event) }); await settle(40) }

describe('한 줄 대기열(PR #43 리뷰 P1·P2)', () => {
  test('리뷰 재현: 읽기 실패 → 버리고 새로(쓰기 늦음) → 그동안 다시 읽기·새 제출 닫힘 → 초기화 끝난 뒤 새 기록 → 덮이지 않아요', async () => {
    const own = slotName(SLOTS, BAR)
    disk.set(own, JSON.stringify(rec('old', '옛 기록')))
    failReads.add(own)
    await mount(h(QuickAddBar))
    expect(alertWith('복구 기록')?.textContent).toContain('읽지 못했어요')
    // 계획(전제 = 못 읽음)과 실행 직전 다시 읽기(여전히 못 읽음)가 같아 그 자리 파일 하나만 써요 — 쓰기는 늦어요
    const open = holdWrite(own)
    await press(alertWith('복구 기록'), '버리고 새로')
    failReads.delete(own)
    // 버리는 중: 단추 없이 안내, 입력·제출 닫힘, 다시 읽기를 불러도 새로 읽지 않아요
    expect(alertWith('버리는 중')).toBeTruthy()
    expect(buttonIn(alertWith('버리는 중'), '다시 읽기')).toBeUndefined()
    expect(barInput().disabled).toBe(true)
    void store.reload(own, anyJson)
    await settle(30)
    expect(store.busy(own)).toBe('reset')
    await enter()
    expect(created.length).toBe(0)
    await open()
    expect(disk.get(own)).toBe('null')
    expect(barInput().disabled).toBe(false)
    await typeInto(barInput(), '새 할 일')
    await enter()
    expect(created).toEqual(['새 할 일'])
    await settle(60)
    const kept = JSON.parse(disk.get(own) ?? 'null')
    expect(isPending(kept) && kept.text).toBe('새 할 일')
  })
  test('다시 읽기를 누르면 바로 "다시 읽는 중"(옛 오류·단추가 남지 않아요) → 끝나면 복원', async () => {
    const own = slotName(SLOTS, BAR)
    disk.set(own, JSON.stringify(rec('r1', '남은 기록 글')))
    failReads.add(own)
    await mount(h(QuickAddBar))
    failReads.delete(own)
    const open = gate(own)
    await press(alertWith('복구 기록'), '다시 읽기')
    expect(alertWith('다시 읽는 중')).toBeTruthy()
    expect(alertWith('읽지 못했어요')).toBeUndefined()
    expect(buttonIn(alertWith('다시 읽는 중'), '버리고 새로')).toBeUndefined()
    await open()
    expect(alertWith('복구 기록')).toBeUndefined()
    expect(barInput().value).toBe('남은 기록 글')
  })
})

describe('자리별 저장(PR #43 리뷰 P1): 한 자리의 깨짐·버리기가 다른 자리에 닿지 않아요', () => {
  for (const broken of ['corrupt', 'read'] as const)
    test('한 줄 자리만 ' + (broken === 'read' ? '읽기 실패' : '깨짐') + ' → 한 줄에서 버리고 새로 → 상세 시트 자리 기록은 그대로', async () => {
      const sheetRec = JSON.stringify(rec('s1', '시트 기록 글'))
      disk.set(slotName(SLOTS, SHEET), sheetRec)
      if (broken === 'corrupt') disk.set(slotName(SLOTS, BAR), 'not json')
      else { disk.set(slotName(SLOTS, BAR), JSON.stringify(rec('b1', '한 줄 기록'))); failReads.add(slotName(SLOTS, BAR)) }
      await mount(h(QuickAddBar))
      await press(alertWith('복구 기록'), '버리고 새로')
      await settle(30)
      expect(fileOf(BAR)).toBe('null')
      expect(fileOf(SHEET)).toBe(sheetRec)
      failReads.clear()
      await remount()
      await mount(sheetEl())
      expect(titleInput().value).toBe('시트 기록 글')
      expect(alertWith('복구 기록')).toBeUndefined()
    })
  test('옛 묶음(자리 파일 없음)은 읽어 넘기고, 한 줄에서 기록을 버려도 묶음 안 시트 기록은 그대로', async () => {
    disk.set(SLOTS, JSON.stringify({ [BAR]: rec('b1', '한 줄 옛 기록'), [SHEET]: rec('s1', '시트 옛 기록') }))
    const bundle = disk.get(SLOTS)
    await mount(h(QuickAddBar))
    expect(barInput().value).toBe('한 줄 옛 기록')
    await click([...document.querySelectorAll('button')].find((b) => (b.textContent ?? '').trim() === '버리기')!)
    await settle(30)
    expect(fileOf(BAR)).toBe('null')
    expect(disk.get(SLOTS)).toBe(bundle)
    await remount()
    await mount(sheetEl())
    expect(titleInput().value).toBe('시트 옛 기록')
  })
  test('옛 묶음 안 다른 자리 항목만 깨졌으면 이 자리는 그대로 읽어요', async () => {
    disk.set(SLOTS, JSON.stringify({ [BAR]: rec('b1', '한 줄 옛 기록'), [SHEET]: { id: 1 } }))
    await mount(h(QuickAddBar))
    expect(alertWith('복구 기록')).toBeUndefined()
    expect(barInput().value).toBe('한 줄 옛 기록')
  })
  test('리뷰 재현(옛 저장 모양): 묶음 안 한 줄 항목만 깨짐 → 한 줄에서 버리고 새로 → 묶음 안 시트 기록은 그대로', async () => {
    disk.set(SLOTS, JSON.stringify({ [BAR]: { id: 1 }, [SHEET]: rec('s1', '시트 옛 기록') }))
    await mount(h(QuickAddBar))
    expect(alertWith('복구 기록')?.textContent).toContain('깨져')
    await press(alertWith('복구 기록'), '버리고 새로')
    await settle(30)
    expect(confirms.at(-1) ?? '').not.toContain('모든 자리')
    await remount()
    await mount(sheetEl())
    expect(titleInput().value).toBe('시트 옛 기록')
  })
  test('옛 묶음 자체가 깨지면 확인창이 그 안 모든 자리가 버려진다고 밝힌 뒤에만 비우고, 자리 파일이 있는 자리는 그대로', async () => {
    disk.set(SLOTS, 'not json')
    const sheetRec = JSON.stringify(rec('s1', '시트 기록 글'))
    disk.set(slotName(SLOTS, SHEET), sheetRec)
    await mount(h(QuickAddBar))
    expect(alertWith('복구 기록')?.textContent).toContain('깨져')
    await press(alertWith('복구 기록'), '버리고 새로')
    await settle(30)
    expect(confirms.at(-1)).toContain('모든 자리')
    expect(disk.get(SLOTS)).toBe('{}')
    expect(fileOf(SHEET)).toBe(sheetRec)
    expect(barInput().disabled).toBe(false)
  })
})

