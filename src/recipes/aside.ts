// Aside 로 깨진 레시피의 새 경로 찾기. 로그인된 브라우저에서 대상 페이지를 열고, 그 페이지가 부른 API 요청과
// 레시피가 아는 후보 경로를 페이지 안에서(쿠키 포함) 불러 본 결과를 한 줄씩 출력하는 스크립트를 만들어 `aside repl --file` 로 돌려요.
// 실행 방식은 board/apps/server/server/runs.ts 를 따라요: ASIDE_BIN·ASIDE_ACCOUNT 환경, NO_COLOR, ANSI 제거, stdout·stderr 끝까지 읽기.
// aside 는 유료·맥 전용이라 테스트에서는 부르지 않아요(AsideRunner 를 바꿔 끼우거나 ASIDE_BIN=/usr/bin/false).
import { mkdtemp, rm, writeFile } from "node:fs/promises"
import { homedir, tmpdir } from "node:os"
import { join } from "node:path"

export const ASIDE_BIN = process.env.ASIDE_BIN || join(homedir(), ".local/bin/aside")
export const ASIDE_ACCOUNT = process.env.ASIDE_ACCOUNT || "u0"
const ANSI = /\x1b\[[0-9;?]*[A-Za-z]/g // oxlint-disable-line no-control-regex -- 터미널 ANSI 이스케이프 제거 (board runs.ts 와 같음)
export const RESULT_PREFIX = "QUORUM_RESULT "

export type AsideResult = { code: number; stdout: string; stderr: string; spawnError?: boolean }
export type AsideRunner = (script: string) => Promise<AsideResult>
/** 스크립트가 후보 하나마다 출력하는 줄의 JSON */
export type AsideProbe = { url: string; status: number; body?: unknown; error?: string }

/**
 * aside repl 스크립트. openTab(startUrl) 뒤 performance 의 resource 항목 중 match 가 들어간 URL 과 probes 를
 * 페이지 안에서 fetch(credentials: include) 해서 "QUORUM_RESULT {json}" 줄로 출력해요.
 */
export function buildDiscoverScript(startUrl: string, match: string, probes: string[], waitMs = 4000): string {
  return `// generated by quorum recipes discover
const startUrl = ${JSON.stringify(startUrl)}
const match = ${JSON.stringify(match)}
const probes = ${JSON.stringify(probes)}
const tab = await openTab(startUrl)
await new Promise((r) => setTimeout(r, ${waitMs}))
const results = await tab.evaluate(async ({ match, probes }) => {
  const seen = performance.getEntriesByType("resource").map((e) => e.name).filter((u) => u.includes(match))
  const urls = [...new Set([...probes, ...seen])].slice(0, 25)
  const out = []
  for (const url of urls) {
    try {
      const r = await fetch(url, { credentials: "include", headers: { accept: "application/json" } })
      let body = null
      try { body = await r.json() } catch {}
      out.push({ url, status: r.status, body })
    } catch (e) { out.push({ url, status: 0, error: String(e) }) }
  }
  return out
}, { match, probes })
for (const r of results) console.log(${JSON.stringify(RESULT_PREFIX)} + JSON.stringify(r))
`
}

export function parseProbes(stdout: string): AsideProbe[] {
  const out: AsideProbe[] = []
  for (const line of stdout.replace(ANSI, "").split("\n")) {
    const at = line.indexOf(RESULT_PREFIX)
    if (at < 0) continue
    try {
      const p = JSON.parse(line.slice(at + RESULT_PREFIX.length)) as AsideProbe
      if (typeof p.url === "string" && typeof p.status === "number") out.push(p)
    } catch { /* 깨진 줄은 후보가 아니에요 */ }
  }
  return out
}

async function readAll(stream: ReadableStream<Uint8Array>): Promise<string> {
  const dec = new TextDecoder()
  let text = ""
  for await (const chunk of stream) text += dec.decode(chunk, { stream: true })
  return text + dec.decode()
}

/** 실제 aside repl 실행기. 스크립트를 임시 파일로 쓰고 `aside repl --account <acct> --file <path>` */
export function asideRunner(opts: { bin?: string; account?: string; timeoutMs?: number } = {}): AsideRunner {
  const bin = opts.bin || ASIDE_BIN
  const account = opts.account || ASIDE_ACCOUNT
  const timeoutMs = opts.timeoutMs ?? 120_000
  return async (script) => {
    const dir = await mkdtemp(join(tmpdir(), "quorum-aside-"))
    const file = join(dir, "discover.js")
    await writeFile(file, script)
    try {
      let proc: ReturnType<typeof Bun.spawn>
      try {
        proc = Bun.spawn([bin, "repl", "--account", account, "--file", file], { stdout: "pipe", stderr: "pipe", stdin: "ignore", env: { ...process.env, NO_COLOR: "1", FORCE_COLOR: "0" } })
      } catch (e) {
        return { code: 127, stdout: "", stderr: String(e), spawnError: true }
      }
      const timer = setTimeout(() => proc.kill("SIGKILL"), timeoutMs)
      try {
        const [stdout, stderr, code] = await Promise.all([readAll(proc.stdout as ReadableStream<Uint8Array>), readAll(proc.stderr as ReadableStream<Uint8Array>), proc.exited])
        return { code, stdout: stdout.replace(ANSI, ""), stderr: stderr.replace(ANSI, "") }
      } finally { clearTimeout(timer) }
    } finally {
      await rm(dir, { recursive: true, force: true })
    }
  }
}
